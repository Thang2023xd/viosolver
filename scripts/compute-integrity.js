/**
 * Compute integrity hashes for extension files + pinned whitelist URL.
 * Run after every release edit: node scripts/compute-integrity.js
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const WHITELIST_URL = 'https://raw.githubusercontent.com/accessgated/keys/refs/heads/main/staff-whitelist.txt';

const FILES = [
  'manifest.json',
  'background.js',
  'content.js',
  'content.css',
  'popup.js',
  'popup.html',
  'interceptor.js'
];

function sha256(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

const fileHashes = {};
for (const rel of FILES) {
  const full = path.join(ROOT, rel);
  if (!fs.existsSync(full)) {
    console.error('Missing file:', rel);
    process.exit(1);
  }
  fileHashes[rel] = sha256(fs.readFileSync(full));
}

const urlHash = sha256(WHITELIST_URL);
const hashesPayload = {
  version: 1,
  whitelistUrl: WHITELIST_URL,
  whitelistUrlHash: urlHash,
  files: fileHashes,
  generatedAt: new Date().toISOString()
};

const hashesJson = JSON.stringify(hashesPayload, null, 2) + '\n';
const hashesPath = path.join(ROOT, 'integrity.hashes.json');
fs.writeFileSync(hashesPath, hashesJson, 'utf8');
const hashesFileHash = sha256(hashesJson);

const pinJs = `/* AUTO-GENERATED by scripts/compute-integrity.js — do not hand-edit */
var INTEGRITY_PIN = {
  whitelistUrl: ${JSON.stringify(WHITELIST_URL)},
  whitelistUrlHash: ${JSON.stringify(urlHash)},
  hashesFile: 'integrity.hashes.json',
  hashesFileHash: ${JSON.stringify(hashesFileHash)}
};
`;

fs.writeFileSync(path.join(ROOT, 'integrity-pin.js'), pinJs, 'utf8');

console.log('Wrote integrity.hashes.json + integrity-pin.js');
console.log('URL hash:', urlHash);
console.log('Hashes file hash:', hashesFileHash);
console.log('Files:', Object.keys(fileHashes).length);
